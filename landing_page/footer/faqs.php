    <h1>Frequently Asked Questions (FAQs)</h1>

    <h2>1. What is this website for?</h2>
    <p>This web-based GIS system, CNO NutriMap, is developed to help the City Nutrition Office (CNO) manage and display health and nutrition data for public awareness, transparency, and informed decision-making.</p>

    <h2>2. Who can use the system?</h2>
    <p>Visitors can explore selected barangay and city-level nutrition data. Authorized personnel from the City and Barangay Nutrition Offices have administrative access to manage and update the data.</p>

    <h2>3. Does the system collect personal information?</h2>
    <p>No personal information is collected from visitors. The system only presents aggregated, non-identifiable health and nutrition data.</p>

    <h2>4. Is my data safe while browsing?</h2>
    <p>Yes. The platform complies with the Data Privacy Act of 2012 (RA 10173) and implements standard web security measures to ensure your privacy and protect non-identifiable data.</p>

